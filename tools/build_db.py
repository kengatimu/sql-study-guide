"""Build the practice database artefacts from db/company.sql.

  * assets/db.js         - the SQL script wrapped as a JS string (loaded by the page,
                           so it also works when index.html is opened straight from disk)
  * db/company.sqlite    - a ready-made SQLite file to open in DB Browser for SQLite

Run from the repo root:  python3 tools/build_db.py
"""
import json
import pathlib
import sqlite3

root = pathlib.Path(__file__).resolve().parent.parent
sql = (root / "db" / "company.sql").read_text(encoding="utf-8")

(root / "assets" / "db.js").write_text(
    "// GENERATED by tools/build_db.py from db/company.sql - do not edit by hand.\n"
    "window.COMPANY_SQL = " + json.dumps(sql, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)

# PostgreSQL flavour: no PRAGMA, real DATE type, exact NUMERIC money
pg = sql.replace("PRAGMA foreign_keys = ON;\n", "")
pg = pg.replace("hire_date       TEXT NOT NULL,            -- ISO format: 'YYYY-MM-DD'",
                "hire_date       DATE NOT NULL,")
pg = pg.replace("salary          REAL NOT NULL,", "salary          NUMERIC(10,2) NOT NULL,")
pg = pg.replace("commission_pct  REAL,", "commission_pct  NUMERIC(4,2),")
pg = pg.replace("Works as-is in SQLite (and DB Browser for SQLite).",
                "PostgreSQL version - run it in pgAdmin's Query Tool (F5).")
assert "PRAGMA" not in pg and "DATE NOT NULL" in pg and "NUMERIC(10,2)" in pg
(root / "db" / "company_postgres.sql").write_text(pg, encoding="utf-8")

target = root / "db" / "company.sqlite"
if target.exists():
    target.unlink()
con = sqlite3.connect(target)
con.executescript(sql)
con.commit()
for table in ["regions", "countries", "locations", "departments", "jobs", "employees", "dependents"]:
    count = con.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
    print(f"{table:12} {count:3} rows")
con.close()
print("built assets/db.js and db/company.sqlite")
